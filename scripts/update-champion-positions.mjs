// Regenerates src/lib/champion-positions.ts from Meraki Analytics' public champion data.
// The source file is ~13 MB, so it is fetched here once instead of at runtime.
// Run after a new champion release: node scripts/update-champion-positions.mjs
import { writeFile } from "node:fs/promises";

const SOURCE = "https://cdn.merakianalytics.com/riot/lol/resources/latest/en-US/champions.json";
const ROLE_BY_POSITION = { TOP: "top", JUNGLE: "jungle", MIDDLE: "mid", BOTTOM: "bottom", SUPPORT: "support" };

const response = await fetch(SOURCE);
if (!response.ok) throw new Error(`Meraki request failed: ${response.status}`);
const champions = await response.json();

const lines = Object.keys(champions)
	.sort((a, b) => a.localeCompare(b))
	.map((id) => {
		const roles = [...new Set((champions[id].positions ?? []).map((position) => ROLE_BY_POSITION[position]).filter(Boolean))];
		return roles.length ? `\t${JSON.stringify(id)}: [${roles.map((role) => JSON.stringify(role)).join(", ")}],` : null;
	})
	.filter(Boolean);

const file = `// Generated by scripts/update-champion-positions.mjs from Meraki Analytics. Do not edit by hand.
// Keys are Data Dragon champion ids. Champions missing here are treated as fitting every role.
import type { DraftRole } from "@/lib/tournament-draft-shared";

export const CHAMPION_POSITIONS: Record<string, DraftRole[]> = {
${lines.join("\n")}
};
`;

await writeFile(new URL("../src/lib/champion-positions.ts", import.meta.url), file);
console.log(`Wrote ${lines.length} champions.`);
